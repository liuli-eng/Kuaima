CREATE TABLE IF NOT EXISTS `job_industry` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `create_by` bigint DEFAULT NULL,
  `date` date DEFAULT NULL,
  `timestamp` datetime(6) DEFAULT NULL,
  `name` varchar(100) NOT NULL COMMENT '行业名称',
  `code` varchar(50) NOT NULL COMMENT '稳定编码',
  `sort_no` int NOT NULL COMMENT '排序号',
  `enabled` bit(1) NOT NULL DEFAULT b'1' COMMENT '是否启用',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_job_industry_name` (`name`),
  UNIQUE KEY `uk_job_industry_code` (`code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `job_enterprise_type` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `create_by` bigint DEFAULT NULL,
  `date` date DEFAULT NULL,
  `timestamp` datetime(6) DEFAULT NULL,
  `industry_id` bigint NOT NULL COMMENT '所属行业ID',
  `name` varchar(100) NOT NULL COMMENT '企业类型名称',
  `sort_no` int NOT NULL COMMENT '排序号',
  `enabled` bit(1) NOT NULL DEFAULT b'1' COMMENT '是否启用',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_job_enterprise_industry_name` (`industry_id`,`name`),
  KEY `idx_job_enterprise_industry` (`industry_id`),
  CONSTRAINT `fk_job_enterprise_industry` FOREIGN KEY (`industry_id`) REFERENCES `job_industry` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `job_category` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `create_by` bigint DEFAULT NULL,
  `date` date DEFAULT NULL,
  `timestamp` datetime(6) DEFAULT NULL,
  `industry_id` bigint NOT NULL COMMENT '所属行业ID',
  `enterprise_type_id` bigint NOT NULL COMMENT '所属企业类型ID',
  `name` varchar(100) NOT NULL COMMENT '工种名称',
  `description` varchar(500) DEFAULT NULL COMMENT '工种描述关键词',
  `sort_no` int NOT NULL COMMENT '排序号',
  `enabled` bit(1) NOT NULL DEFAULT b'1' COMMENT '是否启用',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_job_category_enterprise_name` (`enterprise_type_id`,`name`),
  KEY `idx_job_category_industry` (`industry_id`),
  KEY `idx_job_category_enterprise` (`enterprise_type_id`),
  CONSTRAINT `fk_job_category_industry` FOREIGN KEY (`industry_id`) REFERENCES `job_industry` (`id`),
  CONSTRAINT `fk_job_category_enterprise` FOREIGN KEY (`enterprise_type_id`) REFERENCES `job_enterprise_type` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS `job_category_hot` (
  `id` bigint NOT NULL AUTO_INCREMENT,
  `create_by` bigint DEFAULT NULL,
  `date` date DEFAULT NULL,
  `timestamp` datetime(6) DEFAULT NULL,
  `display_name` varchar(100) NOT NULL COMMENT '热门工种展示名称',
  `job_category_id` bigint DEFAULT NULL COMMENT '关联工种ID',
  `sort_no` int NOT NULL COMMENT '排序号',
  `enabled` bit(1) NOT NULL DEFAULT b'1' COMMENT '是否启用',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_job_category_hot_name` (`display_name`),
  KEY `idx_job_category_hot_job` (`job_category_id`),
  CONSTRAINT `fk_job_category_hot_job` FOREIGN KEY (`job_category_id`) REFERENCES `job_category` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

