ALTER TABLE `payroll_order` ADD COLUMN IF NOT EXISTS `pay_time` DATETIME DEFAULT NULL COMMENT '支付日期（批量转账完成时间）' AFTER `pay_account`;
ALTER TABLE `payroll_order` ADD COLUMN IF NOT EXISTS `reject_reason` VARCHAR(500) DEFAULT NULL COMMENT '驳回原因' AFTER `review_time`;

-- =====================================================================
-- 变更 2: payroll_detail (发薪明细) 新增转账相关字段
-- =====================================================================
ALTER TABLE `payroll_detail` ADD COLUMN IF NOT EXISTS `order_no` VARCHAR(32) DEFAULT NULL COMMENT '转账单号，如 TR20260910001' AFTER `status`;
ALTER TABLE `payroll_detail` ADD COLUMN IF NOT EXISTS `account` VARCHAR(128) DEFAULT NULL COMMENT '支付账户，如 招商银行 · ****6688' AFTER `order_no`;
ALTER TABLE `payroll_detail` ADD COLUMN IF NOT EXISTS `pay_time` DATETIME DEFAULT NULL COMMENT '支付时间' AFTER `account`;

-- 索引（如不存在则添加）
ALTER TABLE `payroll_detail` ADD INDEX IF NOT EXISTS `idx_pd_order_no` (`order_no`);

